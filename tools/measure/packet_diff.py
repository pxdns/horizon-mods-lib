#!/usr/bin/env python3
"""Measures how far 1.21.11 (774) is from Horizon's 26.3 (777), step by step, from Mojang's own data-generator reports.

usage: packet_diff.py REPORTS_DIR HORIZON_IDS_RS [MINECRAFT_DATA_DIR] > report.md

REPORTS_DIR holds one folder per version (1.21.11, 26.1, 26.2, 26.3), each the output of
`java -DbundlerMainClass=net.minecraft.data.Main -jar server.jar --reports --output <folder>` (Java 21 for 1.21.11,
Java 25 for 26.x) with packets.json, registries.json and blocks.json under reports/. tools/measure/run_generator.sh makes them.
HORIZON_IDS_RS is Horizon's crates/horizon-protocol/src/ids.rs, checked against the 26.3 report.
MINECRAFT_DATA_DIR (optional, tools/measure/fetch.py) adds the packet *layout* comparison for 774 -> 775, which the Mojang
reports do not contain.
"""
import json
import re
import sys
from pathlib import Path

reports, ids_rs = Path(sys.argv[1]), Path(sys.argv[2])
mdata = Path(sys.argv[3]) if len(sys.argv) > 3 else None
VERSIONS = [("1.21.11", 774), ("26.1", 775), ("26.2", 776), ("26.3", 777)]


def report(version, name):
    return json.loads((reports / version / "reports" / name).read_text())


def packets(version):
    """{(state, direction): {name: id}}"""
    out = {}
    for state, directions in report(version, "packets.json").items():
        for direction, table in directions.items():
            out[(state, direction)] = {n.removeprefix("minecraft:"): v["protocol_id"] for n, v in table.items()}
    return out


def registry(version, name):
    entries = report(version, "registries.json")[name]["entries"]
    return {n.removeprefix("minecraft:"): v["protocol_id"] for n, v in entries.items()}


def block_states(version):
    blocks = report(version, "blocks.json")
    return {n.removeprefix("minecraft:"): (min(s["id"] for s in b["states"]), len(b["states"])) for n, b in blocks.items()}


def compare(a, b):
    rows = []
    for key in sorted(set(a) | set(b)):
        ta, tb = a.get(key, {}), b.get(key, {})
        common = set(ta) & set(tb)
        rows.append((key, len(ta), len(tb), len(common), sorted(n for n in common if ta[n] != tb[n]),
                     sorted(set(ta) - set(tb)), sorted(set(tb) - set(ta))))
    return rows


def packet_table(title, rows):
    out = [f"### {title}", "", "| State / direction | Packets before | Packets after | In both | Id differs | Removed | Added |", "|---|---:|---:|---:|---:|---:|---:|"]
    for (state, direction), n1, n2, common, moved, removed, added in rows:
        out.append(f"| {state} {direction} | {n1} | {n2} | {common} | {len(moved)} | {len(removed)} | {len(added)} |")
    both = sum(r[3] for r in rows)
    moved = sum(len(r[4]) for r in rows)
    out += ["", f"{both} packets exist in both; {moved} ({100 * moved / max(both, 1):.0f} %) have a different id; "
            f"{sum(len(r[5]) for r in rows)} only before; {sum(len(r[6]) for r in rows)} only after.", ""]
    return out


def names(rows, which):
    out = []
    for (state, direction), _, _, _, _, removed, added in rows:
        items = removed if which == "removed" else added
        if items:
            out.append(f"- {state} {direction}: " + ", ".join(f"`{n}`" for n in items))
    return out or ["- none"]


def registry_row(label, a, b):
    common = set(a) & set(b)
    return (f"| {label} | {len(a)} | {len(b)} | {len(common)} | {sum(1 for n in common if a[n] != b[n])} | {len(set(a) - set(b))} | {len(set(b) - set(a))} |",
            sorted(set(a) - set(b)), sorted(set(b) - set(a)))


def horizon_ids(text):
    out = {}
    state_names = {"handshake", "status", "login", "configuration", "play"}
    for state, body in re.findall(r"pub mod (\w+) \{(.*?)\n\}", text, re.S):
        if state not in state_names:
            continue
        for direction, inner in re.findall(r"pub mod (clientbound|serverbound) \{(.*?)\n    \}", body, re.S):
            m = re.search(r"NAMES: &\[&str\] = &\[(.*?)\];", inner, re.S)
            if m:
                out[(state, direction)] = {n: i for i, n in enumerate(re.findall(r'"([^"]+)"', m.group(1)))}
    return out


P = {v: packets(v) for v, _ in VERSIONS}
out = ["# Measurement: how far 1.21.11 is from Horizon's 26.3", "",
       "Protocol numbers: " + ", ".join(f"{v} = {n}" for v, n in VERSIONS) + ".", "",
       "Generated by `tools/measure/packet_diff.py` from the reports Mojang's own data generator writes for each server jar "
       "(`tools/measure/run_generator.sh`); Horizon's `ids.rs` is checked against the 26.3 report below.", "",
       "## Check: Horizon's packet ids against Mojang's 26.3 report", ""]
mine = horizon_ids(ids_rs.read_text())
mismatch = [f"{k[0]} {k[1]}" for k in set(mine) | set(P["26.3"]) if mine.get(k, {}) != P["26.3"].get(k, {})]
out += [("`ids.rs` matches the 26.3 report exactly for every state and direction." if not mismatch
         else "`ids.rs` differs from the 26.3 report in: " + ", ".join(sorted(mismatch)) + "."), "", "## Packet ids and names", ""]

steps = [(VERSIONS[i][0], VERSIONS[i + 1][0]) for i in range(len(VERSIONS) - 1)]
for a, b in steps:
    out += packet_table(f"{a} -> {b}", compare(P[a], P[b]))
whole = compare(P["1.21.11"], P["26.3"])
out += packet_table("1.21.11 -> 26.3, the whole step", whole)
out += ["Packets only in 1.21.11 (gone in 26.3):", ""] + names(whole, "removed") + ["", "Packets only in 26.3 (added since 1.21.11):", ""] + names(whole, "added") + [""]

out += ["## Registry ids", "", "Numeric ids of items, blocks and entity types are what a translator rewrites inside packets.", ""]
for a, b in steps + [("1.21.11", "26.3")]:
    out += [f"### {a} -> {b}", "", "| Table | Before | After | In both | Id differs | Only before | Only after |", "|---|---:|---:|---:|---:|---:|---:|"]
    extra = []
    for label, reg in (("items", "minecraft:item"), ("blocks", "minecraft:block"), ("entity types", "minecraft:entity_type")):
        row, gone, new = registry_row(label, registry(a, reg), registry(b, reg))
        out.append(row)
        if gone or new:
            extra.append(f"- {label}: only before: {', '.join(gone) or 'none'}; only after: {', '.join(new) or 'none'}")
    sa, sb = block_states(a), block_states(b)
    common = set(sa) & set(sb)
    out += ["", f"Block states: {sum(n for _, n in sa.values())} before, {sum(n for _, n in sb.values())} after; "
            f"{sum(1 for n in common if sa[n][0] != sb[n][0])} blocks start at a different state id; "
            f"{sum(1 for n in common if sa[n][1] != sb[n][1])} have a different number of states.", ""] + extra + [""]

if mdata and (mdata / "1.21.11-protocol.json").exists():
    p774 = json.loads((mdata / "1.21.11-protocol.json").read_text())
    p775 = json.loads((mdata / "26.1-protocol.json").read_text())
    changed = []
    for state in ("handshaking", "status", "login", "configuration", "play"):
        for d in ("toClient", "toServer"):
            t1 = p774.get(state, {}).get(d, {}).get("types", {})
            t2 = p775.get(state, {}).get(d, {}).get("types", {})
            for k in sorted(t1):
                if k.startswith("packet_") and k in t2 and json.dumps(t1[k], sort_keys=True) != json.dumps(t2[k], sort_keys=True):
                    changed.append(f"{state} {d} `{k[7:]}`")
    shared = sum(len(v) for v in (P["1.21.11"]).values())
    out += ["## Packet field layouts, 774 -> 775 (from PrismarineJS/minecraft-data)", "",
            f"The Mojang reports hold ids, not field layouts. In minecraft-data, {len(changed)} of {shared} packets differ in layout between 774 and 775:", ""]
    out += [f"- {c}" for c in changed] + ["", "Layouts for 776 and 777 are not in a machine-readable source: read them from Horizon's decoders "
                                          "(`crates/horizon-protocol/src/packets/play.rs`).", ""]
print("\n".join(out))
